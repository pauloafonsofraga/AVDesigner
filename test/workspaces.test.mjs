test('Enterprise role foundation enforces Owner/Admin/Editor/Viewer boundaries and last-owner safety',async t=>{
  const {db,rpc,asUser}=await workspacesDatabase();t.after(()=>db.close());
  await db.query('insert into auth.users(id,raw_app_meta_data) values($1,$2)',[USER,{wirenexus_provisioned:true}]);
  const wid=(await db.query("insert into public.wirenexus_workspaces(name,kind) values('Team','enterprise') returning id")).rows[0].id;
  await db.query("insert into public.wirenexus_memberships values($1,$2,'owner'),($1,$3,'admin'),($1,$4,'viewer')",[wid,OWNER,STRANGER,USER]);
  const manage=(uid,operation,userId,role)=>rpc(uid)('wirenexus_account',{operation,payload:{workspaceId:wid,userId,role}});
  assert.ok((await manage(USER,'set_member',USER,'owner')).error);
  assert.ok((await manage(STRANGER,'set_member',USER,'owner')).error);
  assert.ok((await manage(STRANGER,'set_member',OWNER,'viewer')).error);
  assert.equal((await manage(STRANGER,'set_member',USER,'editor')).error,null);
  assert.equal((await asUser(STRANGER,tx=>tx.query('update public.wirenexus_workspaces set name=$1 where id=$2 returning id',['Team renamed',wid]))).rows.length,1);
  assert.equal((await asUser(USER,tx=>tx.query('update public.wirenexus_workspaces set name=$1 where id=$2 returning id',['hijack',wid]))).rows.length,0);
  assert.ok((await manage(OWNER,'remove_member',OWNER)).error);
  assert.equal((await manage(OWNER,'set_member',USER,'owner')).error,null);
  assert.equal((await manage(OWNER,'remove_member',OWNER)).error,null);
  const personal=(await rpc(STRANGER)('wirenexus_account')).data.workspaceId;
  assert.ok((await rpc(STRANGER)('wirenexus_account',{operation:'set_member',payload:{workspaceId:personal,userId:USER,role:'viewer'}})).error);
});
test('account-store identity latch cannot carry an old registry into a different signed-in account',async t=>{
  const {db,rpc}=await workspacesDatabase();t.after(()=>db.close());let current=OWNER;
  const store=createAccountLibraryStore({rpc:(...args)=>rpc(current)(...args)});await store.read();current=STRANGER;
  await assert.rejects(store.update(doc=>{doc.preferences={stolen:true};return doc;}),/Account changed/);
  assert.equal((await rpc(STRANGER)('wirenexus_library',{operation:'read'})).data.preferences,undefined);
  let swapOnCommit=false;
  const racing=createAccountLibraryStore({rpc:(name,args)=>rpc(swapOnCommit && args.operation==='commit'?STRANGER:OWNER)(name,args)});
  await racing.read();swapOnCommit=true;
  await assert.rejects(racing.update(doc=>{doc.preferences={staleAccount:true};return doc;}),/Account changed/);
  assert.equal((await rpc(STRANGER)('wirenexus_library',{operation:'read'})).data.preferences,undefined);
});
