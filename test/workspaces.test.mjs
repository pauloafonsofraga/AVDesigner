test('multi-user libraries, direct RLS reads and stale-account operations are isolated',async t=>{
  const {db,rpc,asUser}=await workspacesDatabase();t.after(()=>db.close());
  const a=createAccountLibraryStore({rpc:rpc(OWNER)}),b=createAccountLibraryStore({rpc:rpc(STRANGER)});
  const first=await a.read(),second=await b.read();assert.deepEqual(first.registry,second.registry);
  await a.update(doc=>{doc.preferences={favorites:['private']};return doc;});
  assert.equal((await b.read()).registry.preferences,undefined);
  assert.notEqual(a.identity().workspaceId,b.identity().workspaceId);
  const rows=await asUser(STRANGER,tx=>tx.query('select account_id from wirenexus_private.library'));
  assert.deepEqual(rows.rows.map(r=>r.account_id),[STRANGER]);
  assert.ok((await rpc(null)('wirenexus_library',{operation:'read'})).error);
  assert.equal((await rpc(STRANGER)('wirenexus_library',{operation:'read',payload:{accountId:OWNER,workspaceId:a.identity().workspaceId}})).data.preferences,undefined);
  assert.ok((await rpc(STRANGER)('wirenexus_library',{operation:'commit',payload:{expectedAccountId:OWNER}})).error);
  const own=await asUser(OWNER,tx=>tx.query('select * from public.wirenexus_workspaces'));
  assert.equal(own.rows.length,1);
  assert.equal((await asUser(STRANGER,tx=>tx.query('select * from public.wirenexus_memberships'))).rows.length,1);
  await assert.rejects(asUser(STRANGER,tx=>tx.query("update public.wirenexus_memberships set role='admin'")),/permission denied/);
  await assert.rejects(asUser(null,tx=>tx.query('select * from public.wirenexus_workspaces')),/permission denied/);
  await assert.rejects(asUser(STRANGER,tx=>tx.query('insert into wirenexus_private.platform_admins values($1,now(),$2)',[STRANGER,'forged'])),/permission denied/);
  assert.equal((await asUser(STRANGER,tx=>tx.query('update public.wirenexus_workspaces set name=$1 where personal_owner_id=$2 returning id',['stolen',OWNER]))).rows.length,0);
  await assert.rejects(asUser(OWNER,tx=>tx.query("update public.wirenexus_workspaces set kind='enterprise'")),/permission denied/);
});
