import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { cableTypeSelectionFixture } from "../fixtures/cable-type-selection.mjs";

const { chromium } = createRequire(import.meta.url)(process.env.AVDESIGNER_PLAYWRIGHT_PATH || "playwright");
const browser = await chromium.launch({ headless: true, executablePath: process.env.AVDESIGNER_CHROME_PATH || "/Applications/Google Chrome Dev.app/Contents/MacOS/Google Chrome Dev" });
const screenshots = mkdtempSync(join(tmpdir(), "wirenexus-stagebox-snake-"));
try {
  const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
  const errors = [];page.on("pageerror", e => errors.push(e.message));
  page.on("dialog", dialog => dialog.accept());
  await page.goto(`${process.env.AVDESIGNER_BASE_URL || "http://127.0.0.1:8778"}/index.html`);
  await page.waitForFunction(() => activeEngineBridge()?.ready && localUserSettingsLoaded);
  const project = cableTypeSelectionFixture();project.devices[0].templateOverride.powerWatts = 110;
  await page.evaluate(snapshot => restoreSnapshot(snapshot), project);
  await page.evaluate(() => openDeviceEditorForInstance("source"));
  await page.locator("#editorStageboxSnake").waitFor({ state: "visible" });
  assert.equal(await page.locator("#editorPowerConsumption").isEnabled(), true);
  const before = await page.evaluate(() => ({ connectors: structuredClone(currentEditorTemplate().connectors), connections: structuredClone(state.connections) }));
  await page.locator("#editorStageboxSnakeField label").click();
  assert.equal(await page.locator("#editorStageboxSnake").isChecked(), true);
  assert.equal(await page.locator("#editorPowerConsumption").inputValue(), "0");
  assert.equal(await page.locator("#editorPowerConsumption").isDisabled(), true);
  for (const button of await page.locator("#editorPowerUnitToggle button").all()) assert.equal(await button.isDisabled(), true);
  const enabled = await page.evaluate(() => structuredClone(currentEditorTemplate()));
  assert.deepEqual(enabled.connectors, before.connectors);
  assert.equal(enabled.stageboxSnake.ends.length, 2);
  assert.equal(await page.evaluate(() => undoEditorConnectorMetadata()), true);
  assert.equal(await page.locator("#editorStageboxSnake").isChecked(), false);
  assert.equal(await page.locator("#editorPowerConsumption").isEnabled(), true);
  assert.equal(await page.locator("#editorPowerConsumption").inputValue(), "110");
  assert.equal(await page.evaluate(() => undoEditorConnectorMetadata(true)), true);
  assert.equal(await page.locator("#editorStageboxSnake").isChecked(), true);
  await page.screenshot({ path: join(screenshots, "device-tab.png") });
  await page.locator("#applyDeviceEditor").click();
  await page.waitForFunction(() => templateForInstance(state.devices.find(d => d.instanceId === "source"))?.isStageboxSnake === true);
  await page.evaluate(() => restoreSnapshot(JSON.parse(JSON.stringify(projectSnapshot({ includeClipboardDependencies: true })))));
  await page.evaluate(() => openDeviceEditorForInstance("source"));
  assert.equal(await page.locator("#editorStageboxSnake").isChecked(), true);
  assert.equal(await page.locator("#editorPowerConsumption").isDisabled(), true);
  const reopened = await page.evaluate(() => ({ template: structuredClone(currentEditorTemplate()), connections: structuredClone(state.connections) }));
  assert.deepEqual(reopened.connections, before.connections);
  assert.deepEqual(reopened.template.stageboxSnake, enabled.stageboxSnake);
  await page.locator("#editorStageboxSnakeField label").click();
  assert.equal(await page.locator("#editorStageboxSnake").isChecked(), false);
  assert.equal(await page.locator("#editorPowerConsumption").isEnabled(), true);
  assert.deepEqual(await page.evaluate(() => currentEditorTemplate().stageboxSnake), enabled.stageboxSnake);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ result: "PASS", checks: ["first-tab toggle", "zero power/disabled W+A", "draft undo/redo", "apply/save/reopen", "unchanged cables", "stable ends", "disable/re-enable controls"], screenshots }));
} finally { await browser.close(); }
